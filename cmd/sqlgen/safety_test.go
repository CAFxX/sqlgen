//go:build unix

package main

import (
	"bytes"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"syscall"
	"testing"
)

const safetyYAML = `package: demo
out: demo_gen.go
dialect: sqlite
statements:
  - name: Ping
    kind: exec
    sql: "SELECT :id:int64"
`

func runCLI(t *testing.T, args ...string) (int, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := run(args, &stdout, &stderr)
	return code, stderr.String()
}

func TestGenerateNeverClobbersTheConfigOrHandWrittenFiles(t *testing.T) {
	dir := t.TempDir()
	cfg := filepath.Join(dir, "sqlgen.yaml")
	if err := os.WriteFile(cfg, []byte(safetyYAML), 0o644); err != nil {
		t.Fatal(err)
	}

	// A mistyped -out that names the configuration itself must not turn it into Go code.
	code, stderr := runCLI(t, "-config", cfg, "-out", cfg)
	if code != 1 || !strings.Contains(stderr, "configuration file") {
		t.Fatalf("-out <config>: code=%d stderr=%q, want 1 + a refusal", code, stderr)
	}
	if got, _ := os.ReadFile(cfg); string(got) != safetyYAML {
		t.Fatalf("configuration was overwritten:\n%s", got)
	}

	// Hand-written code that shares the output name is not ours to replace...
	hand := filepath.Join(dir, "demo_gen.go")
	const handSrc = "package demo\n\nfunc Handwritten() {}\n"
	if err := os.WriteFile(hand, []byte(handSrc), 0o644); err != nil {
		t.Fatal(err)
	}
	code, stderr = runCLI(t, "-config", cfg)
	if code != 1 || !strings.Contains(stderr, "not generated by sqlgen") {
		t.Fatalf("hand-written out: code=%d stderr=%q, want 1 + a refusal", code, stderr)
	}
	if got, _ := os.ReadFile(hand); string(got) != handSrc {
		t.Fatalf("hand-written file was overwritten:\n%s", got)
	}

	// ...but an empty placeholder and a previously generated file are.
	for name, content := range map[string]string{"empty": "", "generated": "// Code generated by sqlgen. DO NOT EDIT.\n\npackage demo\n"} {
		if err := os.WriteFile(hand, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		if code, stderr := runCLI(t, "-config", cfg); code != 0 {
			t.Fatalf("%s: code=%d stderr=%q", name, code, stderr)
		}
	}
	if code, stderr := runCLI(t, "-config", cfg, "-check"); code != 0 {
		t.Fatalf("-check after regeneration: code=%d stderr=%q", code, stderr)
	}
}

func TestGenerateWritesThroughSymlinkAndRespectsPermissions(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("symlinks and permission bits")
	}
	dir := t.TempDir()
	cfg := filepath.Join(dir, "sqlgen.yaml")
	if err := os.WriteFile(cfg, []byte(safetyYAML), 0o644); err != nil {
		t.Fatal(err)
	}

	// out is a symlink: the link must survive and its target receive the code.
	if err := os.Mkdir(filepath.Join(dir, "real"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join("real", "target.go"), filepath.Join(dir, "demo_gen.go")); err != nil {
		t.Fatal(err)
	}
	if code, stderr := runCLI(t, "-config", cfg); code != 0 {
		t.Fatalf("code=%d stderr=%q", code, stderr)
	}
	fi, err := os.Lstat(filepath.Join(dir, "demo_gen.go"))
	if err != nil || fi.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("the symlink was replaced by a regular file (%v, %v)", fi, err)
	}
	if got, err := os.ReadFile(filepath.Join(dir, "real", "target.go")); err != nil || !bytes.HasPrefix(got, []byte("// Code generated by sqlgen.")) {
		t.Fatalf("symlink target not written: %v %q", err, got)
	}
	if code, stderr := runCLI(t, "-config", cfg, "-check"); code != 0 {
		t.Fatalf("-check through the symlink: code=%d stderr=%q", code, stderr)
	}

	// An existing file keeps its mode (here owner-only).
	if err := os.Chmod(filepath.Join(dir, "real", "target.go"), 0o600); err != nil {
		t.Fatal(err)
	}
	if code, stderr := runCLI(t, "-config", cfg); code != 0 {
		t.Fatalf("code=%d stderr=%q", code, stderr)
	}
	if fi, _ := os.Stat(filepath.Join(dir, "real", "target.go")); fi.Mode().Perm() != 0o600 {
		t.Fatalf("mode of an existing output changed to %v", fi.Mode().Perm())
	}

	// A new file honours the umask instead of a fixed 0644.
	old := syscall.Umask(0o077)
	defer syscall.Umask(old)
	fresh := filepath.Join(dir, "fresh_gen.go")
	if code, stderr := runCLI(t, "-config", cfg, "-out", fresh); code != 0 {
		t.Fatalf("code=%d stderr=%q", code, stderr)
	}
	if fi, _ := os.Stat(fresh); fi.Mode().Perm() != 0o600 {
		t.Fatalf("new file mode = %v under umask 077, want 0600", fi.Mode().Perm())
	}
	if m, _ := filepath.Glob(filepath.Join(dir, ".sqlgen-*")); len(m) != 0 {
		t.Fatalf("temporary files left behind: %v", m)
	}
}

func TestOutPathWithBackslashIsRejectedWhereSlashIsTheSeparator(t *testing.T) {
	if filepath.Separator != '/' {
		t.Skip("backslash is the separator here")
	}
	dir := t.TempDir()
	cfg := filepath.Join(dir, "sqlgen.yaml")
	if err := os.WriteFile(cfg, []byte(strings.Replace(safetyYAML, "demo_gen.go", `gen\demo_gen.go`, 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{{"-config", cfg}, {"-config", cfg, "-check"}} {
		code, stderr := runCLI(t, args...)
		if code != 1 || !strings.Contains(stderr, "backslash") {
			t.Fatalf("%v: code=%d stderr=%q, want 1 + a backslash diagnostic", args, code, stderr)
		}
	}
	if m, _ := filepath.Glob(filepath.Join(dir, "*")); len(m) != 1 {
		t.Fatalf("a file was created for the backslash path: %v", m)
	}
	// -stdout does not use the path at all.
	if code, stderr := runCLI(t, "-config", cfg, "-stdout"); code != 0 {
		t.Fatalf("-stdout: code=%d stderr=%q", code, stderr)
	}
}
