// Command fixtures renders the integration fixtures that differ only by engine from ONE template each:
// the sqlgen.yaml of every generated test package (pgq/myq/mdbq, fzpg/fzmy/fzsl) and the Go adapters that
// map those packages onto the engine-agnostic test APIs. The output is committed; `make gen` rewrites it and
// `make check` (go run ./fixtures -check) fails on drift.
//
// Run from the integration directory: go run ./fixtures [-check]
package main

import (
	"bytes"
	"embed"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

//go:embed *.tmpl
var templates embed.FS

// engine describes one generated test package. Flavor selects the engine-specific statements of main.yaml.tmpl
// (RETURNING and ::cast support differ); BumpReturning says whether the fuzz fixture has UPDATE ... RETURNING.
type engine struct {
	Pkg, Dialect, Flavor string
	BumpReturning        bool
}

// Title is Pkg with its first letter upper-cased (the suffix of the adapter helper names).
func (e engine) Title() string { return strings.ToUpper(e.Pkg[:1]) + e.Pkg[1:] }

var (
	mainEngines = []engine{
		{Pkg: "pgq", Dialect: "postgres", Flavor: "pg"},
		{Pkg: "myq", Dialect: "mysql", Flavor: "mysql"},
		{Pkg: "mdbq", Dialect: "mariadb", Flavor: "mariadb"},
	}
	adapterEngines = mainEngines[:2] // mdbq is exercised through the myq adapter's statements only
	fuzzEngines    = []engine{
		{Pkg: "fzpg", Dialect: "postgres", BumpReturning: true},
		{Pkg: "fzmy", Dialect: "mariadb"},
		{Pkg: "fzsl", Dialect: "sqlite", BumpReturning: true},
	}
)

type output struct {
	path, tmpl string
	e          engine
}

func outputs() []output {
	var out []output
	for _, e := range mainEngines {
		out = append(out, output{e.Pkg + "/sqlgen.yaml", "main.yaml.tmpl", e})
	}
	for _, e := range adapterEngines {
		out = append(out, output{"adapter_" + e.Pkg + "_test.go", "adapter_test.go.tmpl", e})
	}
	for _, e := range fuzzEngines {
		out = append(out,
			output{e.Pkg + "/sqlgen.yaml", "fuzz.yaml.tmpl", e},
			output{"fuzz_adapter_" + e.Pkg + "_test.go", "fuzz_adapter_test.go.tmpl", e},
			output{"fuzz_bump_" + e.Pkg + "_test.go", "fuzz_bump_test.go.tmpl", e})
	}
	return out
}

func render(o output) ([]byte, error) {
	t, err := template.New(o.tmpl).Delims("<%", "%>").ParseFS(templates, o.tmpl)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	if strings.HasSuffix(o.path, ".go") {
		fmt.Fprintf(&b, "// Code generated by integration/fixtures from %s; DO NOT EDIT.\n\n", o.tmpl)
	}
	if err := t.ExecuteTemplate(&b, o.tmpl, o.e); err != nil {
		return nil, err
	}
	if strings.HasSuffix(o.path, ".go") {
		return format.Source(b.Bytes())
	}
	return b.Bytes(), nil
}

func main() {
	check := flag.Bool("check", false, "fail if a committed output differs from its template instead of rewriting it")
	flag.Parse()
	failed := false
	for _, o := range outputs() {
		want, err := render(o)
		if err != nil {
			fmt.Fprintf(os.Stderr, "fixtures: %s: %v\n", o.path, err)
			os.Exit(1)
		}
		have, _ := os.ReadFile(o.path)
		if bytes.Equal(have, want) {
			continue
		}
		if *check {
			fmt.Fprintf(os.Stderr, "fixtures: %s is out of date with %s (run `make gen`)\n", o.path, o.tmpl)
			failed = true
			continue
		}
		if err := os.MkdirAll(filepath.Dir(o.path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, "fixtures:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(o.path, want, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "fixtures:", err)
			os.Exit(1)
		}
	}
	if failed {
		os.Exit(1)
	}
}
